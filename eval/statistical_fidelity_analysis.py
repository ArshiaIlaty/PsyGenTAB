class StatisticalFidelityAnalyzer:
    """Comprehensive statistical fidelity analyzer for synthetic data"""
    
    def __init__(self, output_dir: str = "statistical_fidelity_results"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True)
        self.results = {}
        
    def kl_divergence(self, p: np.ndarray, q: np.ndarray, epsilon: float = 1e-10) -> float:
        """
        Compute Kullback-Leibler Divergence: KL(P||Q)
        Lower is better (0 = identical distributions)
        """
        p = np.asarray(p, dtype=np.float64) + epsilon
        q = np.asarray(q, dtype=np.float64) + epsilon
        p = p / p.sum()
        q = q / q.sum()
        return np.sum(p * np.log(p / q))
    
    def jensen_shannon_divergence(self, p: np.ndarray, q: np.ndarray) -> float:
        """
        Compute Jensen-Shannon Divergence (symmetric version of KL)
        Range: [0, 1], Lower is better (0 = identical)
        """
        p = np.asarray(p, dtype=np.float64)
        q = np.asarray(q, dtype=np.float64)
        p = p / p.sum()
        q = q / q.sum()
        return jensenshannon(p, q) ** 2  # Squared for consistency with literature
    
    def hellinger_distance(self, p: np.ndarray, q: np.ndarray) -> float:
        """
        Compute Hellinger Distance
        Range: [0, 1], Lower is better (0 = identical)
        """
        p = np.asarray(p, dtype=np.float64)
        q = np.asarray(q, dtype=np.float64)
        p = p / p.sum()
        q = q / q.sum()
        return np.sqrt(np.sum((np.sqrt(p) - np.sqrt(q)) ** 2)) / np.sqrt(2)
    
    def total_variation_distance(self, p: np.ndarray, q: np.ndarray) -> float:
        """
        Compute Total Variation Distance
        Range: [0, 1], Lower is better (0 = identical)
        """
        p = np.asarray(p, dtype=np.float64)
        q = np.asarray(q, dtype=np.float64)
        p = p / p.sum()
        q = q / q.sum()
        return 0.5 * np.sum(np.abs(p - q))
    
    def chi_square_distance(self, p: np.ndarray, q: np.ndarray, epsilon: float = 1e-10) -> float:
        """
        Compute Chi-Square Distance
        Lower is better (0 = identical)
        """
        p = np.asarray(p, dtype=np.float64) + epsilon
        q = np.asarray(q, dtype=np.float64) + epsilon
        return np.sum((p - q) ** 2 / q)
    
    def bhattacharyya_distance(self, p: np.ndarray, q: np.ndarray) -> float:
        """
        Compute Bhattacharyya Distance
        Range: [0, ∞), Lower is better (0 = identical)
        """
        p = np.asarray(p, dtype=np.float64)
        q = np.asarray(q, dtype=np.float64)
        p = p / p.sum()
        q = q / q.sum()
        bc = np.sum(np.sqrt(p * q))
        return -np.log(bc) if bc > 0 else float('inf')
    
    def cramer_v(self, contingency_table: np.ndarray) -> float:
        """
        Compute Cramér's V for categorical association
        Range: [0, 1], Higher indicates stronger association
        """
        chi2 = stats.chi2_contingency(contingency_table)[0]
        n = contingency_table.sum()
        min_dim = min(contingency_table.shape) - 1
        return np.sqrt(chi2 / (n * min_dim)) if min_dim > 0 else 0.0
    
    def energy_distance_metric(self, real: np.ndarray, synthetic: np.ndarray) -> float:
        """
        Compute Energy Distance between two samples
        Lower is better (0 = identical distributions)
        """
        try:
            return energy_distance(real, synthetic)
        except:
            return np.nan
    
    def get_distribution(self, data: np.ndarray, bins: int = 50) -> np.ndarray:
        """Get histogram distribution of continuous data"""
        if len(data) == 0:
            return np.array([])
        hist, _ = np.histogram(data, bins=bins, density=True)
        return hist + 1e-10  # Add small epsilon to avoid zeros
    
    def analyze_continuous_feature(self, real: np.ndarray, synthetic: np.ndarray, 
                                   feature_name: str) -> Dict:
        """Analyze a continuous feature using various metrics"""
        results = {
            'feature': feature_name,
            'type': 'continuous'
        }
        
        try:
            # Remove NaN values
            real = real[~np.isnan(real)]
            synthetic = synthetic[~np.isnan(synthetic)]
            
            if len(real) == 0 or len(synthetic) == 0:
                return results
            
            # Get distributions
            bins = min(50, len(np.unique(real)))
            real_dist = self.get_distribution(real, bins=bins)
            synthetic_dist = self.get_distribution(synthetic, bins=bins)
            
            # Statistical distance metrics
            results['kl_divergence'] = self.kl_divergence(real_dist, synthetic_dist)
            results['js_divergence'] = self.jensen_shannon_divergence(real_dist, synthetic_dist)
            results['hellinger_distance'] = self.hellinger_distance(real_dist, synthetic_dist)
            results['tv_distance'] = self.total_variation_distance(real_dist, synthetic_dist)
            results['chi_square_distance'] = self.chi_square_distance(real_dist, synthetic_dist)
            
            # Wasserstein distance (Earth Mover's Distance)
            results['wasserstein_distance'] = wasserstein_distance(real, synthetic)
            
            # Kolmogorov-Smirnov test
            ks_stat, ks_pval = ks_2samp(real, synthetic)
            results['ks_statistic'] = ks_stat
            results['ks_pvalue'] = ks_pval
            
            # Anderson-Darling test (more sensitive to tails)
            try:
                ad_result = anderson_ksamp([real, synthetic])
                results['anderson_statistic'] = ad_result.statistic
                results['anderson_pvalue'] = ad_result.significance_level
            except:
                results['anderson_statistic'] = np.nan
                results['anderson_pvalue'] = np.nan
            
            # Energy distance
            results['energy_distance'] = self.energy_distance_metric(real, synthetic)
            
            # Bhattacharyya distance
            results['bhattacharyya_distance'] = self.bhattacharyya_distance(real_dist, synthetic_dist)
            
            # Statistical moments
            results['mean_difference'] = abs(np.mean(real) - np.mean(synthetic))
            results['std_difference'] = abs(np.std(real) - np.std(synthetic))
            results['skew_difference'] = abs(stats.skew(real) - stats.skew(synthetic))
            results['kurtosis_difference'] = abs(stats.kurtosis(real) - stats.kurtosis(synthetic))
            
            # Percentile differences (quantile preservation)
            percentiles = [25, 50, 75, 90, 95, 99]
            real_percentiles = np.percentile(real, percentiles)
            synthetic_percentiles = np.percentile(synthetic, percentiles)
            results['percentile_mae'] = np.mean(np.abs(real_percentiles - synthetic_percentiles))
            results['percentile_max_error'] = np.max(np.abs(real_percentiles - synthetic_percentiles))
            
        except Exception as e:
            results['error'] = str(e)
        
        return results
    
    def analyze_categorical_feature(self, real: pd.Series, synthetic: pd.Series,
                                    feature_name: str) -> Dict:
        """Analyze a categorical feature using various metrics"""
        results = {
            'feature': feature_name,
            'type': 'categorical'
        }
        
        try:
            # Get value counts (normalized)
            real_counts = real.value_counts(normalize=True, dropna=True)
            synthetic_counts = synthetic.value_counts(normalize=True, dropna=True)
            
            # Align indices
            all_categories = list(set(real_counts.index) | set(synthetic_counts.index))
            real_dist = np.array([real_counts.get(cat, 0) for cat in all_categories])
            synthetic_dist = np.array([synthetic_counts.get(cat, 0) for cat in all_categories])
            
            # Add epsilon to avoid zeros
            real_dist = real_dist + 1e-10
            synthetic_dist = synthetic_dist + 1e-10
            
            # Normalize
            real_dist = real_dist / real_dist.sum()
            synthetic_dist = synthetic_dist / synthetic_dist.sum()
            
            # Statistical distance metrics
            results['kl_divergence'] = self.kl_divergence(real_dist, synthetic_dist)
            results['js_divergence'] = self.jensen_shannon_divergence(real_dist, synthetic_dist)
            results['hellinger_distance'] = self.hellinger_distance(real_dist, synthetic_dist)
            results['tv_distance'] = self.total_variation_distance(real_dist, synthetic_dist)
            results['chi_square_distance'] = self.chi_square_distance(real_dist, synthetic_dist)
            
            # Chi-square test
            try:
                contingency_table = pd.crosstab(
                    pd.concat([real, synthetic]),
                    pd.Series(['real']*len(real) + ['synthetic']*len(synthetic))
                )
                chi2, pval, dof, expected = chi2_contingency(contingency_table)
                results['chi2_statistic'] = chi2
                results['chi2_pvalue'] = pval
            except:
                pass
            
            # Mutual information
            try:
                # Encode categories as integers
                all_cats = list(set(real) | set(synthetic))
                cat_to_int = {cat: i for i, cat in enumerate(all_cats)}
                real_encoded = [cat_to_int[val] for val in real if val in cat_to_int]
                synthetic_encoded = [cat_to_int[val] for val in synthetic if val in cat_to_int]
                
                # Create contingency table for MI
                min_len = min(len(real_encoded), len(synthetic_encoded))
                results['mutual_information'] = mutual_info_score(
                    real_encoded[:min_len], 
                    synthetic_encoded[:min_len]
                )
            except:
                pass
            
            # Cramér's V for categorical association
            try:
                contingency_table = pd.crosstab(
                    pd.concat([real, synthetic]),
                    pd.Series(['real']*len(real) + ['synthetic']*len(synthetic))
                )
                results['cramer_v'] = self.cramer_v(contingency_table.values)
            except:
                pass
            
            # Category coverage
            real_categories = set(real.dropna().unique())
            synthetic_categories = set(synthetic.dropna().unique())
            results['category_coverage'] = len(synthetic_categories & real_categories) / len(real_categories) if len(real_categories) > 0 else 0
            results['novel_categories'] = len(synthetic_categories - real_categories) / len(synthetic_categories) if len(synthetic_categories) > 0 else 0
            results['missing_categories'] = len(real_categories - synthetic_categories) / len(real_categories) if len(real_categories) > 0 else 0
            
            # Bhattacharyya distance
            results['bhattacharyya_distance'] = self.bhattacharyya_distance(real_dist, synthetic_dist)
            
        except Exception as e:
            results['error'] = str(e)
        
        return results
    
    def analyze_correlation_fidelity(self, real_df: pd.DataFrame, 
                                    synthetic_df: pd.DataFrame) -> Dict:
        """
        Analyze correlation structure preservation.
        CRITICAL FIX: Now includes categorical variables via label encoding.
        """
        results = {}
        
        try:
            # CRITICAL FIX: Include categorical columns via label encoding
            from sklearn.preprocessing import LabelEncoder
            
            # Start with numeric columns
            real_numeric = real_df.select_dtypes(include=[np.number]).copy()
            synthetic_numeric = synthetic_df.select_dtypes(include=[np.number]).copy()
            
            # Get categorical columns
            real_categorical = real_df.select_dtypes(include=['object']).copy()
            synthetic_categorical = synthetic_df.select_dtypes(include=['object']).copy()
            
            # Get common categorical columns
            common_cat_cols = list(set(real_categorical.columns) & set(synthetic_categorical.columns))
            
            # Label encode categorical columns for correlation analysis
            # Use combined vocabulary to ensure alignment
            if len(common_cat_cols) > 0:
                combined_df = pd.concat([real_df[common_cat_cols], synthetic_df[common_cat_cols]], 
                                       axis=0, ignore_index=True)
                
                for col in common_cat_cols:
                    # Fill NaN with mode
                    if combined_df[col].isna().any():
                        mode_val = combined_df[col].mode()[0] if len(combined_df[col].mode()) > 0 else 'Unknown'
                        combined_df[col] = combined_df[col].fillna(mode_val)
                    
                    # Convert to string and encode
                    combined_df[col] = combined_df[col].astype(str)
                    le = LabelEncoder()
                    le.fit(combined_df[col])
                    
                    # Transform real and synthetic separately using same encoder
                    real_cat_col = real_categorical[col].astype(str).fillna(mode_val)
                    synth_cat_col = synthetic_categorical[col].astype(str).fillna(mode_val)
                    
                    # Handle unseen labels
                    real_cat_col = real_cat_col.apply(lambda x: x if x in le.classes_ else le.classes_[0])
                    synth_cat_col = synth_cat_col.apply(lambda x: x if x in le.classes_ else le.classes_[0])
                    
                    real_numeric[f'{col}_encoded'] = le.transform(real_cat_col)
                    synthetic_numeric[f'{col}_encoded'] = le.transform(synth_cat_col)
            
            # Get common columns (now includes encoded categoricals)
            common_cols = list(set(real_numeric.columns) & set(synthetic_numeric.columns))
            
            if len(common_cols) < 2:
                return results
            
            # Compute correlation matrices
            real_corr = real_numeric[common_cols].corr()
            synthetic_corr = synthetic_numeric[common_cols].corr()
            
            # Correlation matrix distance metrics
            results['correlation_frobenius_norm'] = np.linalg.norm(
                real_corr.values - synthetic_corr.values, 'fro'
            )
            results['correlation_mae'] = np.mean(np.abs(real_corr.values - synthetic_corr.values))
            results['correlation_rmse'] = np.sqrt(np.mean((real_corr.values - synthetic_corr.values) ** 2))
            
            # Flatten upper triangular (excluding diagonal)
            mask = np.triu(np.ones_like(real_corr.values), k=1).astype(bool)
            real_corr_flat = real_corr.values[mask]
            synthetic_corr_flat = synthetic_corr.values[mask]
            
            if len(real_corr_flat) > 0:
                results['correlation_pearson'] = stats.pearsonr(real_corr_flat, synthetic_corr_flat)[0]
                results['correlation_spearman'] = stats.spearmanr(real_corr_flat, synthetic_corr_flat)[0]
                
                # Additional correlation metrics
                results['correlation_kendall'] = stats.kendalltau(real_corr_flat, synthetic_corr_flat)[0]
                
                # Correlation sign consistency (how many correlations have the same sign)
                sign_consistency = np.sum(np.sign(real_corr_flat) == np.sign(synthetic_corr_flat)) / len(real_corr_flat)
                results['correlation_sign_consistency'] = sign_consistency
            
            # Track which columns were included
            results['numeric_columns_count'] = len(real_df.select_dtypes(include=[np.number]).columns)
            results['categorical_columns_count'] = len(common_cat_cols)
            results['total_columns_in_correlation'] = len(common_cols)
            
        except Exception as e:
            results['error'] = str(e)
            import traceback
            results['traceback'] = traceback.format_exc()
        
        return results
    
    def analyze_dataset(self, real_path: str, synthetic_path: str, 
                       dataset_name: str) -> Dict:
        """Comprehensive analysis of a dataset"""
        print(f"\n{'='*80}")
        print(f"Analyzing: {dataset_name}")
        print(f"{'='*80}")
        
        # Load data
        try:
            real_df = pd.read_csv(real_path)
            synthetic_df = pd.read_csv(synthetic_path)
        except Exception as e:
            print(f"Error loading data: {e}")
            return {'dataset': dataset_name, 'error': str(e)}
        
        print(f"Real data shape: {real_df.shape}")
        print(f"Synthetic data shape: {synthetic_df.shape}")
        
        results = {
            'dataset': dataset_name,
            'real_samples': len(real_df),
            'synthetic_samples': len(synthetic_df),
            'features': {}
        }
        
        # Analyze each feature
        common_columns = list(set(real_df.columns) & set(synthetic_df.columns))
        print(f"\nAnalyzing {len(common_columns)} common features...")
        
        for col in common_columns:
            print(f"  - {col}...", end=' ')
            
            # Determine if continuous or categorical
            if real_df[col].dtype in ['int64', 'float64']:
                # Check if it's actually categorical (few unique values)
                if len(real_df[col].unique()) <= 20:
                    feature_results = self.analyze_categorical_feature(
                        real_df[col], synthetic_df[col], col
                    )
                else:
                    feature_results = self.analyze_continuous_feature(
                        real_df[col].values, synthetic_df[col].values, col
                    )
            else:
                feature_results = self.analyze_categorical_feature(
                    real_df[col], synthetic_df[col], col
                )
            
            results['features'][col] = feature_results
            print("✓")
        
        # Correlation analysis
        print("\nAnalyzing correlation structure...")
        correlation_results = self.analyze_correlation_fidelity(real_df, synthetic_df)
        results['correlation_fidelity'] = correlation_results
        
        # Compute aggregate metrics
        print("\nComputing aggregate metrics...")
        results['aggregate_metrics'] = self.compute_aggregate_metrics(results['features'])
        
        return results
    
    def compute_aggregate_metrics(self, feature_results: Dict) -> Dict:
        """Compute aggregate metrics across all features"""
        metrics = {}
        
        metric_names = [
            'kl_divergence', 'js_divergence', 'hellinger_distance',
            'tv_distance', 'chi_square_distance', 'wasserstein_distance',
            'ks_statistic', 'bhattacharyya_distance', 'energy_distance',
            'anderson_statistic'
        ]
        
        for metric_name in metric_names:
            values = []
            for feature, results in feature_results.items():
                if metric_name in results:
                    val = results[metric_name]
                    # Only aggregate over numeric values; skip strings/None/NaN-safe
                    if isinstance(val, (int, float, np.floating)) and not np.isnan(val):
                        values.append(float(val))
            
            if values:
                metrics[f'mean_{metric_name}'] = float(np.mean(values))
                metrics[f'median_{metric_name}'] = float(np.median(values))
                metrics[f'std_{metric_name}'] = float(np.std(values))
                metrics[f'max_{metric_name}'] = np.max(values)
                metrics[f'min_{metric_name}'] = np.min(values)
        
        return metrics
    

"""
Comprehensive Statistical Fidelity Analysis for Synthetic Data
================================================================

This script analyzes synthetic data generated by different fine-tuned models
using various statistical fidelity metrics including:
- KL Divergence (Kullback-Leibler)
- Jensen-Shannon Divergence
- Wasserstein Distance (Earth Mover's Distance)
- Total Variation Distance
- Hellinger Distance
- Chi-Square Distance
- Kolmogorov-Smirnov Statistic
- Correlation Distance
- Mutual Information
"""

import pandas as pd
import numpy as np
from scipy import stats
from scipy.spatial.distance import jensenshannon, euclidean

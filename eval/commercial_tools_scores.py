def evaluate_dataset_pair(
    dataset_name: str,
    model_name: str,
    original_path: Path,
    synthetic_path: Path,
    target_column: str,
    verbose: bool = True,
    skip_if_exists: bool = False,
    skip_components: list = None
) -> Dict:
    """
    Evaluate a single original-synthetic dataset pair.
    
    Args:
        dataset_name: Name of the dataset
        model_name: Name of the model (alm or rtf)
        original_path: Path to original dataset CSV
        synthetic_path: Path to synthetic dataset CSV
        target_column: Name of the target column
        verbose: Whether to print progress
    
    Returns:
        Dictionary containing evaluation results
    """
    # Check if results file already exists
    result_file = OUTPUT_DIR / f"{dataset_name}_{model_name}_evaluation.json"
    existing_results = {}
    
    # Load existing results to merge with new results (for components not being skipped)
    if result_file.exists():
        try:
            with open(result_file, "r") as f:
                existing_results = json.load(f)
            if verbose:
                print(f"\n✓ Found existing results file: {result_file}")
                if skip_components:
                    print(f"  Loading existing results (will skip: {', '.join(skip_components)})...")
                elif skip_if_exists:
                    print(f"  Loading existing results (will skip all completed components)...")
                else:
                    print(f"  Loading existing results (will merge with new results)...")
        except Exception as e:
            if verbose:
                print(f"  Warning: Could not load existing results: {e}")
    
    if verbose:
        print(f"\n{'='*80}")
        print(f"Evaluating {model_name.upper()} on {dataset_name}")
        print(f"{'='*80}")
    
    evaluation_start = datetime.now().isoformat()
    start_time = time.time()
    
    # Start with existing results or create new
    results = existing_results.copy() if existing_results else {
        "dataset_name": dataset_name,
        "model_name": model_name,
        "original_data_path": str(original_path),
        "synthetic_data_path": str(synthetic_path),
        "target_column": target_column,
        "evaluation_start": evaluation_start,
    }
    
    # Update evaluation start time
    results["evaluation_start"] = evaluation_start
    
    try:
        # Check if files exist
        if not original_path.exists():
            raise FileNotFoundError(f"Original data file not found: {original_path}")
        if not synthetic_path.exists():
            raise FileNotFoundError(f"Synthetic data file not found: {synthetic_path}")
        
        if verbose:
            print(f"✓ Original data: {original_path}")
            print(f"✓ Synthetic data: {synthetic_path}")
        
        # Load data
        real_df = pd.read_csv(original_path)
        synthetic_df = pd.read_csv(synthetic_path)
        
        if verbose:
            print(f"  Real data shape: {real_df.shape}")
            print(f"  Synthetic data shape: {synthetic_df.shape}")
        
        # Verify target column exists
        if target_column not in real_df.columns:
            raise ValueError(f"Target column '{target_column}' not found in original data")
        
        # 1. Statistical Fidelity Analysis
        if "statistical_fidelity" in skip_components:
            if verbose:
                print("\n1. Skipping Statistical Fidelity Analysis (requested)...")
            if "statistical_fidelity" not in results:
                results["statistical_fidelity"] = {"skipped": True}
        elif "statistical_fidelity" in results and skip_if_exists and "error" not in results.get("statistical_fidelity", {}):
            # Only skip if --skip-all-existing was used
            if verbose:
                print("\n1. Skipping Statistical Fidelity Analysis (already completed)...")
        else:
            if verbose:
                print("\n1. Running Statistical Fidelity Analysis...")
            
            try:
                # Create output directory first
                stat_output_dir = OUTPUT_DIR / dataset_name / model_name / "statistical"
                stat_output_dir.mkdir(parents=True, exist_ok=True)
                
                analyzer = StatisticalFidelityAnalyzer(
                    output_dir=str(stat_output_dir)
                )
                
                fidelity_results = analyzer.analyze_dataset(
                    real_path=str(original_path),
                    synthetic_path=str(synthetic_path),
                    dataset_name=f"{dataset_name}_{model_name}"
                )
                results["statistical_fidelity"] = fidelity_results
                
                if verbose:
                    if "aggregate_metrics" in fidelity_results:
                        agg = fidelity_results["aggregate_metrics"]
                        kl_div = agg.get('mean_kl_divergence', None)
                        js_div = agg.get('mean_js_divergence', None)
                        hellinger = agg.get('mean_hellinger_distance', None)  # Fixed: was 'mean_hellinger'
                        
                        print(f"  Mean KL Divergence: {kl_div if kl_div is not None else 'N/A'}")
                        print(f"  Mean JS Divergence: {js_div if js_div is not None else 'N/A'}")
                        print(f"  Mean Hellinger Distance: {hellinger if hellinger is not None else 'N/A'}")
            except Exception as e:
                if verbose:
                    print(f"  ✗ Statistical fidelity analysis failed: {e}")
                results["statistical_fidelity"] = {"error": str(e)}
                import traceback
                results["statistical_fidelity"]["traceback"] = traceback.format_exc()
        
        # 2. Comprehensive Evaluation (ML Utility, Privacy, etc.)
        if "comprehensive" in skip_components or "ml_utility" in skip_components:
            if verbose:
                print("\n2. Skipping Comprehensive Evaluation (requested)...")
            if "statistical_comparison" not in results:
                results["statistical_comparison"] = {"skipped": True}
            if "ml_utility" not in results:
                results["ml_utility"] = {"skipped": True}
        elif ("statistical_comparison" in results or "ml_utility" in results) and skip_if_exists:
            # Only skip if --skip-all-existing was used
            if verbose:
                print("\n2. Skipping Comprehensive Evaluation (already completed)...")
        else:
            if verbose:
                print("\n2. Running Comprehensive Evaluation...")
            
            try:
                evaluator = ComprehensiveDatasetEvaluator(
                    dataset_name=f"{dataset_name}_{model_name}",
                    real_csv=str(original_path),
                    synthetic_csv=str(synthetic_path),
                    target_column=target_column
                )
                
                if evaluator.load_data():
                    # Run statistical comparison
                    stats_comp = evaluator.statistical_comparison()
                    results["statistical_comparison"] = stats_comp
                    
                    # Run ML utility evaluation
                    ml_results = evaluator.machine_learning_utility()
                    results["ml_utility"] = ml_results
                
                    # Run privacy evaluation (if available)
                    # Note: Privacy evaluation can be slow for large datasets
                    if "privacy" in skip_components:
                        if verbose:
                            print("  Skipping privacy evaluation (requested)...")
                        if "privacy" not in results:
                            results["privacy"] = {"skipped": True}
                    elif "privacy" in results and skip_if_exists and "error" not in results.get("privacy", {}):
                        # Only skip if --skip-all-existing was used
                        if verbose:
                            print("  Skipping privacy evaluation (already completed)...")
                    else:
                        try:
                            if verbose:
                                print("  Running privacy evaluation (this may take a while for large datasets)...")
                            privacy_start = time.time()
                            privacy_results = evaluator.privacy_evaluation()
                            privacy_duration = time.time() - privacy_start
                            privacy_results["evaluation_duration_seconds"] = privacy_duration
                            results["privacy"] = privacy_results
                            if verbose:
                                print(f"  Privacy evaluation completed in {privacy_duration:.1f} seconds")
                        except KeyboardInterrupt:
                            if verbose:
                                print("  ⚠ Privacy evaluation interrupted by user")
                            results["privacy"] = {"error": "Interrupted by user"}
                        except Exception as e:
                            if verbose:
                                print(f"  Privacy evaluation not available: {e}")
                            results["privacy"] = {"error": str(e)}
                    
                    if verbose:
                        if ml_results:
                            if "real_to_synthetic" in ml_results:
                                # Extract best accuracy
                                best_acc = 0
                                for technique, tech_results in ml_results["real_to_synthetic"].items():
                                    for model_name_ml, model_results in tech_results.items():
                                        if isinstance(model_results, dict) and "accuracy" in model_results:
                                            best_acc = max(best_acc, model_results["accuracy"])
                                if best_acc > 0:
                                    print(f"  Best ML Accuracy: {best_acc:.4f}")
                else:
                    if verbose:
                        print("  ✗ Failed to load data in evaluator")
                    results["comprehensive_evaluation"] = {"error": "Failed to load data"}
            except Exception as e:
                if verbose:
                    print(f"  ✗ Comprehensive evaluation failed: {e}")
                results["comprehensive_evaluation"] = {"error": str(e)}
                import traceback
                results["comprehensive_evaluation"]["traceback"] = traceback.format_exc()
        
        # 3. SDMetrics Evaluation
        if "sdmetrics" in skip_components:
            if verbose:
                print("\n3. Skipping SDMetrics Evaluation (requested)...")
            if "sdmetrics" not in results:
                results["sdmetrics"] = {"skipped": True}
        elif "sdmetrics" in results and skip_if_exists and "error" not in results.get("sdmetrics", {}):
            # Only skip if --skip-all-existing was used
            if verbose:
                print("\n3. Skipping SDMetrics Evaluation (already completed)...")
        elif SDMETRICS_AVAILABLE:
            if verbose:
                print("\n3. Running SDMetrics Evaluation...")
            try:
                sdmetrics_results = evaluate_with_sdmetrics(
                    str(original_path), str(synthetic_path), verbose
                )
                results["sdmetrics"] = sdmetrics_results
                
                if verbose and "quality_score" in sdmetrics_results.get("sdmetrics", {}):
                    qs = sdmetrics_results["sdmetrics"]["quality_score"]
                    ds = sdmetrics_results["sdmetrics"].get("diagnostic_score", "N/A")
                    print(f"  Quality Score: {qs:.4f}")
                    print(f"  Diagnostic Score: {ds:.4f}" if isinstance(ds, (int, float)) else f"  Diagnostic Score: {ds}")
            except Exception as e:
                if verbose:
                    print(f"  ✗ SDMetrics evaluation failed: {e}")
                results["sdmetrics"] = {"error": str(e)}
        else:
            if verbose:
                print("  ⚠ SDMetrics not available (skipping)")
            results["sdmetrics"] = {"error": "SDMetrics not installed"}
        
        # 4. MostlyAI QA Evaluation
        if "mostlyai_qa" in skip_components or "mostlyai" in skip_components:
            if verbose:
                print("\n4. Skipping MostlyAI QA Evaluation (requested)...")
            if "mostlyai_qa" not in results:
                results["mostlyai_qa"] = {"skipped": True}
        elif "mostlyai_qa" in results and skip_if_exists and "error" not in results.get("mostlyai_qa", {}):
            # Only skip if --skip-all-existing was used
            if verbose:
                print("\n4. Skipping MostlyAI QA Evaluation (already completed)...")
        elif MOSTLYAI_AVAILABLE:
            if verbose:
                print("\n4. Running MostlyAI QA Evaluation...")
            try:
                mostlyai_results = evaluate_with_mostlyai(
                    str(original_path), str(synthetic_path), target_column, verbose
                )
                results["mostlyai_qa"] = mostlyai_results
                
                if verbose and "overall_accuracy" in mostlyai_results.get("mostlyai_qa", {}):
                    oa = mostlyai_results["mostlyai_qa"]["overall_accuracy"]
                    print(f"  Overall Accuracy: {oa:.4f}")
            except Exception as e:
                if verbose:
                    print(f"  ✗ MostlyAI QA evaluation failed: {e}")
                results["mostlyai_qa"] = {"error": str(e)}
        else:
            if verbose:
                print("  ⚠ MostlyAI not available (skipping)")
            results["mostlyai_qa"] = {"error": "MostlyAI not installed"}
        
        # Add timing information
        end_time = time.time()
        evaluation_end = datetime.now().isoformat()
        
        results["evaluation_end"] = evaluation_end
        results["evaluation_duration_seconds"] = end_time - start_time
        
        if verbose:
            print(f"\n✓ Evaluation completed in {results['evaluation_duration_seconds']:.2f} seconds")
        
        return results
        
    except Exception as e:
        # Track error
        end_time = time.time()
        error_result = {
            "dataset_name": dataset_name,
            "model_name": model_name,
            "error": str(e),
            "evaluation_start": evaluation_start,
            "evaluation_end": datetime.now().isoformat(),
            "evaluation_duration_seconds": end_time - start_time,
        }
        
        if verbose:
            print(f"✗ Evaluation error: {e}")
            import traceback
            traceback.print_exc()
            error_result["traceback"] = traceback.format_exc()
        
        return error_result


def evaluate_with_sdmetrics(real_path: str, synthetic_path: str, verbose: bool = True) -> Dict:
    """Evaluate using SDMetrics."""
    try:
        # Import here to ensure it's available
        from sdmetrics.reports.single_table import DiagnosticReport, QualityReport
        try:
            from sdv.metadata import SingleTableMetadata
        except ImportError:
            from sdmetadata import SingleTableMetadata
        
        real_data = pd.read_csv(real_path)
        synthetic_data = pd.read_csv(synthetic_path)
        
        # Ensure common columns
        common_cols = list(set(real_data.columns) & set(synthetic_data.columns))
        real_data = real_data[common_cols].copy()
        synthetic_data = synthetic_data[common_cols].copy()
        
        # Generate metadata
        metadata = SingleTableMetadata()
        metadata.detect_from_dataframe(real_data)
        
        # Diagnostic report
        if verbose:
            print("  Generating diagnostic report...")
        diagnostic = DiagnosticReport()
        diagnostic.generate(real_data, synthetic_data, metadata.to_dict())
        diagnostic_score = diagnostic.get_score()
        
        # Quality report
        if verbose:
            print("  Generating quality report...")
        quality = QualityReport()
        quality.generate(real_data, synthetic_data, metadata.to_dict())
        quality_score = quality.get_score()
        
        # Get details - SDMetrics returns DataFrames
        diagnostic_details = None
        quality_details = None
        try:
            diagnostic_details_df = diagnostic.get_details()
            if diagnostic_details_df is not None and hasattr(diagnostic_details_df, 'to_dict'):
                # Convert DataFrame to dict format
                diagnostic_details = diagnostic_details_df.to_dict('records')
            elif diagnostic_details_df is not None:
                # If it's already a dict or list
                diagnostic_details = diagnostic_details_df
        except Exception as e:
            if verbose:
                print(f"  Warning: Could not extract diagnostic details: {e}")
        
        try:
            quality_details_df = quality.get_details()
            if quality_details_df is not None and hasattr(quality_details_df, 'to_dict'):
                # Convert DataFrame to dict format
                quality_details = quality_details_df.to_dict('records')
            elif quality_details_df is not None:
                # If it's already a dict or list
                quality_details = quality_details_df
        except Exception as e:
            if verbose:
                print(f"  Warning: Could not extract quality details: {e}")
        
        return {
            "sdmetrics": {
                "diagnostic_score": float(diagnostic_score),
                "quality_score": float(quality_score),
                "diagnostic_details": diagnostic_details,
                "quality_details": quality_details,
            }
        }
    except Exception as e:
        import traceback
        return {
            "sdmetrics": {
                "error": str(e),
                "traceback": traceback.format_exc()
            }
        }


def evaluate_with_mostlyai(real_path: str, synthetic_path: str, target_column: str, verbose: bool = True) -> Dict:
    """Evaluate using MostlyAI QA."""
    try:
        from sklearn.model_selection import train_test_split
        
        # Load data
        real_data = pd.read_csv(real_path)
        synthetic_data = pd.read_csv(synthetic_path)
        
        # Ensure common columns
        common_cols = list(set(real_data.columns) & set(synthetic_data.columns))
        real_data = real_data[common_cols].copy()
        synthetic_data = synthetic_data[common_cols].copy()
        
        # Split real data into train/holdout (70/30)
        if verbose:
            print("  Splitting real data into train/holdout...")
        
        # For classification tasks, use stratified split
        if target_column in real_data.columns:
            try:
                train_data, holdout_data = train_test_split(
                    real_data,
                    test_size=0.3,
                    random_state=42,
                    stratify=real_data[target_column]
                )
            except ValueError:
                # If stratification fails, use regular split
                train_data, holdout_data = train_test_split(
                    real_data,
                    test_size=0.3,
                    random_state=42
                )
        else:
            train_data, holdout_data = train_test_split(
                real_data,
                test_size=0.3,
                random_state=42
            )
        
        if verbose:
            print(f"  Train: {train_data.shape}, Holdout: {holdout_data.shape}, Synthetic: {synthetic_data.shape}")
            print("  Running MostlyAI QA report (this may take a while)...")
        
        # Run MostlyAI QA - Correct API uses syn_tgt_data, trn_tgt_data, hol_tgt_data
        report_path, metrics = qa.report(
            syn_tgt_data=synthetic_data,
            trn_tgt_data=train_data,
            hol_tgt_data=holdout_data
        )
        
        # Extract metrics from report
        # qa.report() returns (report_path, metrics) tuple
        metrics_dict = {}
        try:
            # Convert metrics to dict if it's a Pydantic model or similar
            if hasattr(metrics, "model_dump"):
                metrics_dict = metrics.model_dump()
            elif hasattr(metrics, "dict"):
                metrics_dict = metrics.dict()
            elif isinstance(metrics, dict):
                metrics_dict = metrics
            else:
                # Try to extract common attributes
                if hasattr(metrics, 'overall_accuracy'):
                    metrics_dict["overall_accuracy"] = float(metrics.overall_accuracy)
                if hasattr(metrics, 'univariate_accuracy'):
                    metrics_dict["univariate_accuracy"] = float(metrics.univariate_accuracy)
                if hasattr(metrics, 'bivariate_accuracy'):
                    metrics_dict["bivariate_accuracy"] = float(metrics.bivariate_accuracy)
                if hasattr(metrics, 'dcr'):
                    metrics_dict["dcr"] = float(metrics.dcr)
                if hasattr(metrics, 'nndr'):
                    metrics_dict["nndr"] = float(metrics.nndr)
        except Exception as e:
            if verbose:
                print(f"  Warning: Could not extract all metrics: {e}")
        
        return {
            "mostlyai_qa": {
                "metrics": metrics_dict,
                "report_path": str(report_path) if report_path else None,
                "report_available": True
            }
        }
    except Exception as e:
        import traceback
        return {
            "mostlyai_qa": {
                "error": str(e),
                "traceback": traceback.format_exc()
            }
        }


